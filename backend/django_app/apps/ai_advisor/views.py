# Initialize Gemini
GEMINI_AVAILABLE = False
if settings.GEMINI_API_KEY and len(settings.GEMINI_API_KEY) > 20:
    try:
        genai.configure(api_key=settings.GEMINI_API_KEY)
        gemini_model = genai.GenerativeModel('gemini-2.0-flash')
        GEMINI_AVAILABLE = True
    except Exception:
        pass

class ChatView(views.APIView):
    permission_classes = [IsAuthenticated]

    def post(self, request):
        messages = request.data.get('messages', [])
        
        if not GEMINI_AVAILABLE:
            return Response({
                "response": "⚠️ **Configuration Needed!**\nPlease add a valid `GEMINI_API_KEY` to your backend `.env` file."
            })

        store = Store.objects.get(user=request.user)
        inventory = InventoryItem.objects.filter(store=store)
        
        # Build context
        total_items = inventory.count()
        total_value = sum(item.selling_price * item.quantity for item in inventory)
        low_stock = [item.name for item in inventory if 0 < item.quantity <= 5]
        
        system_context = f"""
        You are TechStock-AI, an expert inventory advisor for PC hardware retailers.
        Current Store: {store.name}
        Total Products: {total_items}
        Total Value: ₹{total_value}
        Low Stock Items: {', '.join(low_stock) if low_stock else 'None'}
        """

        try:
            chat = gemini_model.start_chat(history=[])
            prompt = f"System Context: {system_context}\n\nUser: {messages[-1]['content']}"
            response = chat.send_message(prompt)
            
            return Response({
                "response": response.text
            })
        except Exception as e:
            return Response({"response": f"AI Error: {str(e)}"}, status=status.HTTP_500_INTERNAL_SERVER_ERROR)

