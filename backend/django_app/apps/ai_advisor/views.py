class DashboardView(views.APIView):
    permission_classes = [IsAuthenticated]

    def get(self, request):
        store = Store.objects.get(user=request.user)
        inventory = InventoryItem.objects.filter(store=store)
        
        total_value = sum(item.selling_price * item.quantity for item in inventory)
        low_stock = inventory.filter(quantity__gt=0, quantity__lte=5).count()
        out_of_stock = inventory.filter(quantity=0).count()
        
        # Mock analytics for phase 2
        return Response({
            "stats": {
                "total_inventory_value": total_value,
                "total_items": inventory.count(),
                "monthly_revenue": 150000,
                "monthly_profit": 25000,
                "avg_margin": 18.5,
                "dead_stock_count": 0,
                "low_stock_count": low_stock,
                "out_of_stock_count": out_of_stock
            },
            "ai_insight": None,
            "recommendations": [],
            "alerts": [],
            "recent_sales": [],
            "category_distribution": []
        })

